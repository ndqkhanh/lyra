class TestPerformanceBenchmarks:
    """E2E performance benchmark tests."""

    @pytest.mark.e2e
    @pytest.mark.benchmark
    def test_quick_research_latency(self, tmp_path, benchmark):
        """Benchmark quick research latency."""
        output_dir = tmp_path / "research"
        output_dir.mkdir()

        def run_quick_research():
            orchestrator = ResearchOrchestrator(output_dir=output_dir)
            return orchestrator.research(
                topic="LLM agents",
                depth="quick",
                sources=["arxiv"]
            )

        result = benchmark(run_quick_research)
        assert result.is_complete

    @pytest.mark.e2e
    @pytest.mark.benchmark
    def test_standard_research_throughput(self, tmp_path, mock_discovery_results):
        """Benchmark standard research throughput."""
        output_dir = tmp_path / "research"
        output_dir.mkdir()

        orchestrator = ResearchOrchestrator(output_dir=output_dir)

        start_time = datetime.now(timezone.utc)

        with patch.object(orchestrator.discovery, 'discover', return_value=mock_discovery_results["standard"]):
            progress = orchestrator.research(
                topic="Multi-agent systems",
                depth="standard",
                sources=["arxiv"]
            )

        elapsed = (datetime.now(timezone.utc) - start_time).total_seconds()

        # Calculate throughput
        total_sources = sum(progress.sources_found.values())
        sources_per_second = total_sources / elapsed if elapsed > 0 else 0

        assert sources_per_second > 0.1  # At least 0.1 sources/second


