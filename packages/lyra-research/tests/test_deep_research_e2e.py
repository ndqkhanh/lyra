        output_dir = tmp_path / "research"
        output_dir.mkdir()

        orchestrator = ResearchOrchestrator(output_dir=output_dir)

        # Simulate API error with mock
        with patch.object(orchestrator.discovery, 'discover') as mock_discover:
            # First call fails, second succeeds
            from lyra_research.discovery import ResearchSource, SourceType
            mock_source = ResearchSource(
                id="test-1",
                title="Test Paper",
                source_type=SourceType.PAPER,
                url="https://arxiv.org/abs/test",
                abstract="Test abstract"
            )
            mock_discover.side_effect = [
                RuntimeError("API error"),
                {"arxiv": [mock_source]}
            ]

            progress = orchestrator.research(
                topic="LLM agents",
                depth="quick",
                sources=["arxiv"]
            )

            # Should recover via retry mechanism
            assert progress.tasks_retried >= 0  # Coordination manager tracks retries

