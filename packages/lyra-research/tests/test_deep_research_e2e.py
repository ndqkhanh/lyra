class TestQuickResearchMode:
    """E2E tests for quick research mode."""

    @pytest.mark.e2e
    @pytest.mark.slow
    def test_quick_research_complete_workflow(self, tmp_path, mock_discovery_results):
        """Test complete quick research workflow (10 sources, 1 hop)."""
        output_dir = tmp_path / "research"
        output_dir.mkdir()

        orchestrator = ResearchOrchestrator(output_dir=output_dir)

        # Mock discovery to avoid real API calls
        with patch.object(orchestrator.discovery, 'discover', return_value=mock_discovery_results["quick"]):
            # Execute quick research
            progress = orchestrator.research(
                topic="LLM tool use",
                depth="quick",
                sources=["arxiv"]
            )

        # Verify completion
        assert progress.is_complete
        assert progress.error is None

        # Verify report generated
        assert progress.report is not None
        assert progress.report.topic == "LLM tool use"
        assert len(progress.report.executive_summary) > 0

        # Verify source limits (quick mode fetches ~15 sources)
        total_sources = sum(progress.sources_found.values())
        assert total_sources <= 20

        # Verify performance (2 minutes max)
        assert progress.elapsed_seconds < 120

        # Verify quality
        assert progress.report.quality_score >= 0.0

